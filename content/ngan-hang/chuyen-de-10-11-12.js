// Câu trả lời ngắn có `template` sinh được biến thể số liệu: {{ten_bien}} trong văn bản được thay bằng giá trị.
// Nhập vào website: npm run nap-ngan-hang -- content/ngan-hang/chuyen-de-10-11-12.js
const r = String.raw;
const SOURCE = 'Ngân hàng chuyên đề Vật Lý Example24';

const ROUNDING = {
  0: '(làm tròn kết quả đến chữ số hàng đơn vị)',
  1: '(làm tròn kết quả đến chữ số hàng phần mười)',
  2: '(làm tròn kết quả đến chữ số hàng phần trăm)',
};

// Đặc tả biến: v(min, max, step, value, decimals hiển thị)
function v(min, max, step, value, decimals) {
  const dec = decimals ?? (String(step).split('.')[1] || '').length;
  return { min, max, step, value, decimals: dec };
}

// Bộ tạo câu hỏi cho một chủ đề — khoá tự đánh số: cd-<topic>-<type>-<nn>
function topic(key) {
  const grade = Number(key.slice(2, 4));
  const counters = { mcq: 0, tf: 0, short: 0 };
  const nextKey = (type) => {
    counters[type] += 1;
    return `cd-${key}-${type}-${String(counters[type]).padStart(2, '0')}`;
  };
  return {
    mcq(family, difficulty, stem, options, answer, explanation) {
      return {
        key: nextKey('mcq'), source: SOURCE, family, type: 'mcq', grade, topic: key, difficulty,
        stem, data: { options, answer }, explanation,
      };
    },
    tf(family, difficulty, stem, statements, answers, explanation) {
      return {
        key: nextKey('tf'), source: SOURCE, family, type: 'tf', grade, topic: key, difficulty,
        stem, data: { statements, answers }, explanation,
      };
    },
    // opts: { decimals, unit, constants, context }
    short(family, difficulty, stem, vars, answer, opts, explanation) {
      const decimals = opts.decimals;
      const q = {
        key: nextKey('short'), source: SOURCE, family, type: 'short', grade, topic: key, difficulty,
        stem: `${stem} ${ROUNDING[decimals]}`,
        explanation,
        data: { decimals, unit: opts.unit || '' },
        template: { vars, answer },
      };
      if (opts.context) q.context = opts.context;
      if (opts.constants) q.template.constants = opts.constants;
      return q;
    },
  };
}

